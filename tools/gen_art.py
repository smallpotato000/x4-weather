#!/usr/bin/env python3
"""Generates include/ArtBits.h: the 1bpp bitmaps the UI draws itself.

Both are BW1 (set bit = ink), which is what FreeInkUI's forEachBitmapPixel()
expects, so no polarity folding is needed at the call site.

  cat  — a sleeping black cat, curled up, eyes closed, tail wrapped round.
  gear — the settings affordance in the data pages' header strip.

Run from the project root:  python3 tools/gen_art.py
"""
import pathlib

from PIL import Image, ImageChops, ImageDraw

OUT = pathlib.Path('include/ArtBits.h')
CAT_W, CAT_H = 460, 300
GEAR_SIZE = 40


def cat_image() -> Image.Image:
    img = Image.new('L', (CAT_W, CAT_H), 0)   # 0 = paper, 255 = ink
    d = ImageDraw.Draw(img)

    # Body: a loaf, wide and low.
    d.ellipse([60, 120, 440, 290], fill=255)
    # Chest bump so the head has something to rest on.
    d.ellipse([90, 140, 300, 290], fill=255)
    # Head, tucked down against the chest.
    d.ellipse([55, 80, 215, 235], fill=255)
    # Ears: two triangles poking up from the head.
    d.polygon([(80, 100), (96, 46), (140, 92)], fill=255)
    d.polygon([(140, 92), (186, 50), (198, 108)], fill=255)
    # Tail wrapping from the back, around the front, tip resting on the belly.
    d.arc([210, 150, 470, 330], start=285, end=95, fill=255, width=30)
    d.ellipse([200, 258, 250, 296], fill=255)

    # Closed eyes: two shallow arcs, cut back to paper.
    d.arc([95, 138, 128, 168], start=20, end=160, fill=0, width=5)
    d.arc([150, 138, 183, 168], start=20, end=160, fill=0, width=5)
    # Nose + mouth, paper-coloured detail.
    d.polygon([(132, 178), (146, 178), (139, 186)], fill=0)
    d.arc([126, 182, 152, 200], start=20, end=160, fill=0, width=4)
    # Whiskers.
    for dy in (-4, 6, 16):
        d.line([(60, 190 + dy), (112, 184 + dy)], fill=0, width=4)
        d.line([(166, 184 + dy), (212, 190 + dy)], fill=0, width=4)
    return img


def gear_image() -> Image.Image:
    import math
    img = Image.new('L', (GEAR_SIZE, GEAR_SIZE), 0)
    c = GEAR_SIZE / 2
    # Eight teeth around a ring: short and narrow, so it reads as a cog and not
    # as a flower at this size. Drawn on a scratch layer per tooth and merged.
    for k in range(8):
        tooth = Image.new('L', (GEAR_SIZE, GEAR_SIZE), 0)
        ImageDraw.Draw(tooth).rectangle([c - 3.5, 3, c + 3.5, 9], fill=255)
        tooth = tooth.rotate(-k * 45, center=(c, c), resample=Image.BICUBIC)
        img = ImageChops.lighter(img, tooth)
    d = ImageDraw.Draw(img)
    d.ellipse([c - 13, c - 13, c + 13, c + 13], fill=255)           # body
    d.ellipse([c - 5, c - 5, c + 5, c + 5], fill=0)                 # axle hole
    return img


def to_bits(img: Image.Image, threshold: int = 128) -> list[int]:
    w, h = img.size
    data = img.load()
    out = []
    for y in range(h):
        for byte in range((w + 7) // 8):
            value = 0
            for bit in range(8):
                x = byte * 8 + bit
                if x < w and data[x, y] >= threshold:
                    value |= 0x80 >> bit
            out.append(value)
    return out


def emit(name: str, img: Image.Image, lines: list[str]) -> None:
    w, h = img.size
    bits = to_bits(img)
    lines.append(f'inline constexpr uint16_t {name}Width = {w};')
    lines.append(f'inline constexpr uint16_t {name}Height = {h};')
    lines.append(f'inline constexpr uint8_t {name}Bits[] = {{')
    per_line = 24
    for i in range(0, len(bits), per_line):
        row = ', '.join(f'0x{b:02X}' for b in bits[i:i + per_line])
        lines.append(f'    {row},')
    lines.append('};')
    lines.append('')


def main() -> None:
    cat, gear = cat_image(), gear_image()
    # Trim the cat to its ink so the layout can spend every pixel of the lower
    # half on the drawing instead of on empty canvas.
    bbox = cat.getbbox()
    if bbox:
        cat = cat.crop(bbox)
    # Preview sheets for a human to look at.
    cat.resize((cat.width // 2, cat.height // 2)).save('build/preview/art-cat.png')
    gear.resize((128, 128), Image.NEAREST).save('build/preview/art-gear.png')

    lines = [
        '#pragma once',
        '',
        '// Hand-drawn 1bpp art for the data pages (generated by tools/gen_art.py).',
        '// Format is BW1: a set bit is ink, matching FreeInkUI.',
        '',
        '#if FREEINK_DEVICE_PAPERS3',
        '',
        '#include <stdint.h>',
        '',
        'namespace weather {',
        'namespace art {',
        '',
    ]
    emit('kCat', cat, lines)
    emit('kGear', gear, lines)
    lines += ['}  // namespace art', '}  // namespace weather', '', '#endif  // FREEINK_DEVICE_PAPERS3', '']
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT} ({OUT.stat().st_size} B): cat {cat.size}, gear {gear.size}')
    print(f'  cat bits: {len(to_bits(cat))} B, gear bits: {len(to_bits(gear))} B')


if __name__ == '__main__':
    main()
